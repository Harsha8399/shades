import { Candle, MarketContext, Signal, Pattern, Timeframe } from '../types';
import { DetectedSignal, DecisionTrace, PredictionSnapshot } from '../types/decision';
import { CandidateSignal } from '../types/prediction';
import { PatternRegistry } from './PatternRegistry';
import { calculateATR, detectTrend, getVolatilityRegime } from '../indicators';
import { TradeFilters, FilterConfig, DEFAULT_FILTER_CONFIG } from './TradeFilters';

function uuid(): string {
  return `cand_${Date.now()}_${Math.random().toString(36).slice(2, 11)}`;
}

/**
 * Result of detailed pattern detection including candidates before filters
 */
export interface DetailedDetectionResult {
  /** Signals that passed all trade filters (final predictions) */
  signals: DetectedSignal[];
  /** All candidate signals generated by patterns (before trade filters) */
  candidates: CandidateSignal[];
  /** All decision traces for diagnostics */
  traces: DecisionTrace[];
}

/**
 * Pattern detection engine
 * Runs all registered patterns against candle data
 */
export class PatternEngine {
  private registry: PatternRegistry;
  private filterConfig: FilterConfig;
  private useFilters: boolean;
  
  constructor(
    registry?: PatternRegistry,
    filterConfig?: Partial<FilterConfig>,
    useFilters: boolean = true
  ) {
    this.registry = registry || PatternRegistry.getInstance();
    this.filterConfig = { ...DEFAULT_FILTER_CONFIG, ...filterConfig };
    this.useFilters = useFilters;
  }
  
  /**
   * Enable/disable trade filters
   */
  setFiltersEnabled(enabled: boolean): void {
    this.useFilters = enabled;
  }
  
  /**
   * Update filter configuration
   */
  updateFilterConfig(config: Partial<FilterConfig>): void {
    this.filterConfig = { ...this.filterConfig, ...config };
  }
  
  /**
   * Build market context from candles
   */
  buildMarketContext(candles: Candle[], symbol: string, timeframe: MarketContext['timeframe']): MarketContext {
    return {
      symbol,
      timeframe,
      atr: calculateATR(candles, 14),
      trend: detectTrend(candles, 4),
      volatility: getVolatilityRegime(candles, 14, 50),
    };
  }
  
  /**
   * Run enabled patterns on candles and collect decision traces.
   * Returns signals enriched with the trace/snapshot evidence that produced them,
   * plus all candidate signals before trade filter application.
   * @param htfCandles - Optional higher timeframe candles for MTF analysis
   * @param opts.strategyId - When set, only this strategy runs (used by replay)
   */
  detectSignalsDetailed(
    candles: Candle[],
    symbol: string,
    timeframe: Timeframe,
    htfCandles?: Candle[],
    opts?: { strategyId?: string; absoluteCandleIndex?: number }
  ): DetailedDetectionResult {
    const signals: DetectedSignal[] = [];
    const candidates: CandidateSignal[] = [];
    const traces: DecisionTrace[] = [];
    
    // Build market context
    const context = this.buildMarketContext(candles, symbol, timeframe);
    
    // Build trade filters if enabled
    const filters = this.useFilters 
      ? new TradeFilters(candles, htfCandles ?? null, '4h', timeframe, this.filterConfig)
      : null;
    
    // Get patterns applicable to this timeframe and symbol
    const patterns = this.registry.getEnabled().filter(p => 
      p.config.timeframes.includes(timeframe) &&
      (p.config.symbols.length === 0 || p.config.symbols.includes(symbol)) &&
      (!opts?.strategyId || p.id === opts.strategyId)
    );
    
    // Run each pattern
    for (const pattern of patterns) {
      try {
        // Validate pattern has enough data
        const validation = pattern.validate(candles);
        if (!validation.isValid) {
          // Record a trace explaining the insufficient-data failure
          if (validation.errors.length > 0) {
            traces.push({
              strategyId: pattern.id,
              strategyVersion: pattern.version,
              candleIndex: opts?.absoluteCandleIndex ?? Math.max(0, candles.length - 1),
              timestamp: candles[candles.length - 1]?.timestamp ?? 0,
              symbol,
              timeframe,
              outcome: 'NO_SIGNAL',
              stages: [{
                id: 'data_sufficient',
                label: 'Sufficient candle history',
                result: 'FAIL',
                detail: validation.errors.join(', '),
                values: { candlesAvailable: candles.length },
              }],
              conditions: [{
                id: 'data_sufficient',
                label: 'Sufficient candle history',
                evaluated: true,
                passed: false,
                detail: validation.errors.join(', '),
                values: { candlesAvailable: candles.length },
              }],
            });
          }
          continue;
        }
        
        // Reset trace/snapshot before detection
        if ('lastTrace' in pattern) {
          const traceOwner = pattern as unknown as { lastTrace: DecisionTrace | null; lastSnapshot: PredictionSnapshot | null };
          traceOwner.lastTrace = null;
          traceOwner.lastSnapshot = null;
        }
        
        // Detect signal
        let signal = pattern.detectSignal(candles, context, opts?.absoluteCandleIndex) as DetectedSignal | null;
        
        // Attach trace/snapshot evidence produced by the pattern
        const traceOwner = pattern as { lastTrace?: DecisionTrace | null; lastSnapshot?: unknown };
        if (traceOwner.lastTrace) {
          traces.push(traceOwner.lastTrace);
          if (signal) {
            signal.trace = traceOwner.lastTrace;
            signal.snapshot = (traceOwner.lastSnapshot as DetectedSignal['snapshot']) ?? undefined;
          }
        }
        
        if (signal) {
          // Create candidate signal BEFORE trade filters
          const candidate: CandidateSignal = {
            id: uuid(),
            timestamp: signal.timestamp,
            symbol,
            timeframe,
            strategyId: pattern.id,
            strategyName: pattern.name,
            direction: signal.direction,
            entryPrice: signal.entryPrice ?? candles[candles.length - 1].close,
            stopLoss: signal.stopLoss,
            target: signal.target,
            confidence: signal.confidence,
            confluenceFactors: [...signal.confluenceFactors],
            invalidationPrice: signal.invalidationPrice,
            riskRewardRatio: signal.riskRewardRatio,
            candleIndex: opts?.absoluteCandleIndex ?? candles.length - 1,
            trace: signal.trace,
            snapshot: signal.snapshot,
            status: 'PENDING_FILTERS',
          };
          
          // Apply trade filters if enabled
          if (filters) {
            const filterResult = filters.applyAll(signal);
            
            candidate.filterResult = {
              passed: filterResult.pass,
              failedFilters: filterResult.failedFilters,
              results: filterResult.results,
              totalConfidenceAdjustment: filterResult.totalConfidenceAdjustment,
            };
            
            if (!filterResult.pass) {
              console.log(`[PatternEngine] Signal filtered out: ${pattern.name} - ${filterResult.failedFilters.join(', ')}`);
              // Update trace outcome to FILTERED
              if (signal.trace) {
                signal.trace.outcome = 'FILTERED';
              }
              // Update candidate status
              candidate.status = 'FILTERED';
              candidate.rejectionReason = `Rejected by trade filters: ${filterResult.failedFilters.join(', ')}`;
              // Still record the trace for diagnostics
              traces.push({
                ...signal.trace!,
                outcome: 'FILTERED',
                entryPrice: signal.entryPrice,
                stopLoss: signal.stopLoss,
                target: signal.target,
                failedFilters: filterResult.failedFilters,
              });
            } else {
              // Adjust confidence based on filter results
              signal.confidence = Math.min(1, Math.max(0, 
                signal.confidence + filterResult.totalConfidenceAdjustment
              ));
              
              // Add filter confluence factors
              for (const result of filterResult.results) {
                if (result.pass && result.confidence > 0) {
                  signal.confluenceFactors.push(result.filter);
                }
              }
              
              candidate.status = 'ACCEPTED';
              signals.push(signal);
              console.log(`[PatternEngine] Signal detected: ${pattern.name} - ${signal.direction} (conf: ${(signal.confidence * 100).toFixed(0)}%)`);
            }
          } else {
            // No filters enabled - candidate is accepted
            candidate.status = 'ACCEPTED';
            signals.push(signal);
            console.log(`[PatternEngine] Signal detected: ${pattern.name} - ${signal.direction} (conf: ${(signal.confidence * 100).toFixed(0)}%)`);
          }
          
          candidates.push(candidate);
        }
      } catch (error) {
        console.error(`[PatternEngine] Error running pattern ${pattern.id}:`, error);
        traces.push({
          strategyId: pattern.id,
          strategyVersion: pattern.version,
          candleIndex: opts?.absoluteCandleIndex ?? Math.max(0, candles.length - 1),
          timestamp: candles[candles.length - 1]?.timestamp ?? 0,
          symbol,
          timeframe,
          outcome: 'ERROR',
          stages: [{
            id: 'error',
            label: 'Strategy execution',
            result: 'FAIL',
            detail: error instanceof Error ? error.message : String(error),
          }],
          conditions: [],
          error: error instanceof Error ? error.message : String(error),
        });
      }
    }
    
    return { signals, candidates, traces };
  }
  
  /**
   * Run all enabled patterns on candles
   * Returns array of detected signals (after trade filters)
   * @param htfCandles - Optional higher timeframe candles for MTF analysis
   */
  detectSignals(
    candles: Candle[],
    symbol: string,
    timeframe: Timeframe,
    htfCandles?: Candle[]
  ): Signal[] {
    return this.detectSignalsDetailed(candles, symbol, timeframe, htfCandles).signals;
  }
  
  /**
   * Run a specific pattern
   * @param htfCandles - Optional higher timeframe candles for MTF analysis
   */
  runPattern(
    patternId: string,
    candles: Candle[],
    symbol: string,
    timeframe: Timeframe,
    htfCandles?: Candle[]
  ): Signal | null {
    const pattern = this.registry.get(patternId);
    
    if (!pattern) {
      console.error(`Pattern ${patternId} not found`);
      return null;
    }
    
    if (!pattern.config.enabled) {
      console.warn(`Pattern ${patternId} is disabled`);
      return null;
    }
    
    const context = this.buildMarketContext(candles, symbol, timeframe);
    const validation = pattern.validate(candles);
    
    if (!validation.isValid) {
      console.warn(`Pattern validation failed: ${validation.errors.join(', ')}`);
      return null;
    }
    
    let signal = pattern.detectSignal(candles, context);
    
    // Apply filters if enabled
    if (signal && this.useFilters) {
      const filters = new TradeFilters(candles, htfCandles ?? null, '4h', timeframe, this.filterConfig);
      const filterResult = filters.applyAll(signal);
      
      if (!filterResult.pass) {
        console.log(`[PatternEngine] Signal filtered: ${filterResult.failedFilters.join(', ')}`);
        return null;
      }
      
      signal.confidence = Math.min(1, Math.max(0, 
        signal.confidence + filterResult.totalConfidenceAdjustment
      ));
    }
    
    return signal;
  }
  
  /**
   * Get current filter analysis for a symbol
   */
  getFilterAnalysis(
    candles: Candle[],
    htfCandles?: Candle[]
  ): TradeFilters {
    return new TradeFilters(candles, htfCandles ?? null, '4h', '1h', this.filterConfig);
  }
  
  /**
   * Get minimum required candles for a specific strategy or all enabled patterns
   * @param strategyId - Optional strategy ID to get requirement for a specific strategy
   */
  getMinRequiredCandles(strategyId?: string): number {
    let patterns = this.registry.getEnabled();
    
    if (strategyId) {
      patterns = patterns.filter(p => p.id === strategyId);
    }
    
    if (patterns.length === 0) return 100;
    
    return Math.max(...patterns.map(p => p.getRequiredCandleCount()));
  }
  
  /**
   * Get a pattern by its ID
   */
  getPattern(patternId: string): Pattern | undefined {
    return this.registry.get(patternId);
  }
  
  /**
   * Validate candles are sufficient for pattern detection
   */
  validateCandles(candles: Candle[]): { valid: boolean; required: number; actual: number } {
    const required = this.getMinRequiredCandles();
    return {
      valid: candles.length >= required,
      required,
      actual: candles.length,
    };
  }
}

export default PatternEngine;

